    תלמיד_א.הוסף_ציון(92);
    תלמיד_א.הוסף_ציון(88);
    תלמיד_א.הדפס_פרטים();

    // ------------------------------------------------------------
    // דוגמאות נוספות
    // ------------------------------------------------------------

    הדגם_מפה();
    הדגם_אלגוריתמים();
