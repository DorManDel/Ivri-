    ציונים.הוסף(95);

    הדפס << "אחרי הוספה: ";
    עברי::הדפס_וקטור(ציונים);

    הדפס << "סכום ציונים: " << חשב_סכום(ציונים) << סוף_שורה;
    הדפס << "ממוצע ציונים: " << חשב_ממוצע(ציונים) << סוף_שורה;

    // ------------------------------------------------------------
    // מחלקה בעברית
    // ------------------------------------------------------------

    עברי::כותרת("דוגמה: מחלקה תלמיד");

    תלמיד תלמיד_א("דור");
